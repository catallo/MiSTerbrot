#!/usr/bin/env python3
"""Emit rtl/palette_names.vh: the overlay's palette-name ROM init (M10K) from tools/palette_names.txt.

One 200-bit word (25 ASCII chars, string-literal layout, space padded) per
palette index; 128-deep so every 7-bit address is defined ("Unused" beyond the
catalogue).  text_overlay.v reads it with a 2-stage synchronous ROM read, which
replaced the 90-way constant mux that used to be evaluated per pixel
(ALM diet, 2026-10-12).  Edit tools/palette_names.txt, rerun this script.
"""
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "palette_names.txt"
OUT = ROOT / "rtl" / "palette_names.vh"
CHARS, DEPTH = 25, 128
names = [l.rstrip("\n") for l in SRC.read_text().splitlines() if l.strip()]
assert len(names) <= DEPTH and all(len(n) <= CHARS for n in names), "name too long / too many"
lines = ["// AUTO-GENERATED by tools/palette_names_encode.py from tools/palette_names.txt — do not edit.",
         f"// {len(names)} palettes, {CHARS} chars each, ROM depth {DEPTH}.",
         "", f"`define PALETTE_NAME_CHARS {CHARS}", f"`define PALETTE_NAME_W {CHARS*8}", "",
         "`define PALETTE_NAME_INIT \\"]
for i in range(DEPTH):
    s = (names[i] if i < len(names) else "Unused").ljust(CHARS)
    word = int.from_bytes(s.encode("ascii"), "big")
    lines.append(f"    pal_name_rom[{i:<3}] = {CHARS*8}'h{word:0{CHARS*2}X}; /* {s.rstrip()} */ \\")
lines[-1] = lines[-1].rstrip(" \\")
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT} ({len(names)} names)")
